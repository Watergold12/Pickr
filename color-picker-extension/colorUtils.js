export class ColorUtils {
    static getClosestColorName(r, g, b) {
        let minDistance = Infinity;
        let closestName = "unknown";
        for (const [name, rgb] of Object.entries(CSS_COLORS)) {
            // Simple Euclidean distance in RGB space
            const dr = r - rgb[0];
            const dg = g - rgb[1];
            const db = b - rgb[2];
            const dist = dr * dr + dg * dg + db * db;
            if (dist < minDistance) {
                minDistance = dist;
                closestName = name;
            }
        }
        return closestName;
    }

    static toHex(r, g, b) {
        return `#${r.toString(16).padStart(2, '0')}${g.toString(16).padStart(2, '0')}${b.toString(16).padStart(2, '0')}`.toUpperCase();
    }

    static toRgb(r, g, b) {
        return `rgb(${r}, ${g}, ${b})`;
    }

    static toRgbPercent(r, g, b) {
        return `rgb(${(r / 2.55).toFixed(2)}%, ${(g / 2.55).toFixed(2)}%, ${(b / 2.55).toFixed(2)}%)`;
    }

    static toHsl(r, g, b) {
        let r_ = r / 255, g_ = g / 255, b_ = b / 255;
        let max = Math.max(r_, g_, b_), min = Math.min(r_, g_, b_);
        let h, s, l = (max + min) / 2;
        if (max == min) {
            h = s = 0;
        } else {
            let d = max - min;
            s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
            switch (max) {
                case r_: h = (g_ - b_) / d + (g_ < b_ ? 6 : 0); break;
                case g_: h = (b_ - r_) / d + 2; break;
                case b_: h = (r_ - g_) / d + 4; break;
            }
            h /= 6;
        }
        return `hsl(${(h * 360).toFixed(2)}, ${(s * 100).toFixed(2)}%, ${(l * 100).toFixed(2)}%)`;
    }

    static toHsv(r, g, b) {
        let r_ = r / 255, g_ = g / 255, b_ = b / 255;
        let max = Math.max(r_, g_, b_), min = Math.min(r_, g_, b_);
        let h, s, v = max;
        let d = max - min;
        s = max == 0 ? 0 : d / max;
        if (max == min) {
            h = 0;
        } else {
            switch (max) {
                case r_: h = (g_ - b_) / d + (g_ < b_ ? 6 : 0); break;
                case g_: h = (b_ - r_) / d + 2; break;
                case b_: h = (r_ - g_) / d + 4; break;
            }
            h /= 6;
        }
        return `hsv(${(h * 360).toFixed(2)}, ${(s * 100).toFixed(2)}%, ${(v * 100).toFixed(2)}%)`;
    }

    static toCmyk(r, g, b) {
        let c = 1 - (r / 255);
        let m = 1 - (g / 255);
        let y = 1 - (b / 255);
        let k = Math.min(c, Math.min(m, y));
        
        if (k == 1) {
            return `cmyk(0%, 0%, 0%, 100%)`;
        }
        
        c = (c - k) / (1 - k);
        m = (m - k) / (1 - k);
        y = (y - k) / (1 - k);
        return `cmyk(${(c * 100).toFixed(2)}%, ${(m * 100).toFixed(2)}%, ${(y * 100).toFixed(2)}%, ${(k * 100).toFixed(2)}%)`;
    }

    static toHwb(r, g, b) {
        let r_ = r / 255, g_ = g / 255, b_ = b / 255;
        let max = Math.max(r_, g_, b_), min = Math.min(r_, g_, b_);
        let h;
        if (max == min) {
            h = 0;
        } else {
            let d = max - min;
            switch (max) {
                case r_: h = (g_ - b_) / d + (g_ < b_ ? 6 : 0); break;
                case g_: h = (b_ - r_) / d + 2; break;
                case b_: h = (r_ - g_) / d + 4; break;
            }
            h /= 6;
        }
        let w = min;
        let black = 1 - max;
        return `hwb(${(h * 360).toFixed(2)}, ${(w * 100).toFixed(2)}%, ${(black * 100).toFixed(2)}%)`;
    }

    // RGB to XYZ (D65 illuminant, sRGB profile)
    static toXyzParams(r, g, b) {
        let r_ = r / 255, g_ = g / 255, b_ = b / 255;
        r_ = r_ > 0.04045 ? Math.pow((r_ + 0.055) / 1.055, 2.4) : r_ / 12.92;
        g_ = g_ > 0.04045 ? Math.pow((g_ + 0.055) / 1.055, 2.4) : g_ / 12.92;
        b_ = b_ > 0.04045 ? Math.pow((b_ + 0.055) / 1.055, 2.4) : b_ / 12.92;
        
        r_ *= 100; g_ *= 100; b_ *= 100;
        
        let x = r_ * 0.4124 + g_ * 0.3576 + b_ * 0.1805;
        let y = r_ * 0.2126 + g_ * 0.7152 + b_ * 0.0722;
        let z = r_ * 0.0193 + g_ * 0.1192 + b_ * 0.9505;
        return [x, y, z];
    }

    static toXyz(r, g, b) {
        let [x, y, z] = this.toXyzParams(r, g, b);
        return `XYZ(${x.toFixed(2)}, ${y.toFixed(2)}, ${z.toFixed(2)})`;
    }

    // XYZ to Lab (D65)
    static toLabParams(r, g, b) {
        let [x, y, z] = this.toXyzParams(r, g, b);
        x /= 95.047;
        y /= 100.000;
        z /= 108.883;
        
        x = x > 0.008856 ? Math.pow(x, 1/3) : (7.787 * x) + (16 / 116);
        y = y > 0.008856 ? Math.pow(y, 1/3) : (7.787 * y) + (16 / 116);
        z = z > 0.008856 ? Math.pow(z, 1/3) : (7.787 * z) + (16 / 116);
        
        let l = (116 * y) - 16;
        let a = 500 * (x - y);
        let b_ = 200 * (y - z);
        return [l, a, b_];
    }

    static toLab(r, g, b) {
        let [l, a, b_] = this.toLabParams(r, g, b);
        return `lab(${l.toFixed(2)}, ${a.toFixed(2)}, ${b_.toFixed(2)})`;
    }

    static toLch(r, g, b) {
        let [l, a, b_] = this.toLabParams(r, g, b);
        let c = Math.sqrt(a * a + b_ * b_);
        let h = Math.atan2(b_, a) * (180 / Math.PI);
        if (h < 0) h += 360;
        return `lch(${l.toFixed(2)}, ${c.toFixed(2)}, ${h.toFixed(2)})`;
    }

    // sRGB to OKLAB
    static toOklabParams(r, g, b) {
        // Convert to linear sRGB
        let r_ = r / 255, g_ = g / 255, b_ = b / 255;
        r_ = r_ > 0.04045 ? Math.pow((r_ + 0.055) / 1.055, 2.4) : r_ / 12.92;
        g_ = g_ > 0.04045 ? Math.pow((g_ + 0.055) / 1.055, 2.4) : g_ / 12.92;
        b_ = b_ > 0.04045 ? Math.pow((b_ + 0.055) / 1.055, 2.4) : b_ / 12.92;

        let l = 0.4122214708 * r_ + 0.5363325363 * g_ + 0.0514459929 * b_;
        let m = 0.2119034982 * r_ + 0.6806995451 * g_ + 0.1073969566 * b_;
        let s = 0.0883024619 * r_ + 0.2817188376 * g_ + 0.6299787005 * b_;

        let l_ = Math.cbrt(l);
        let m_ = Math.cbrt(m);
        let s_ = Math.cbrt(s);

        let L = 0.2104542553*l_ + 0.7936177850*m_ - 0.0040720468*s_;
        let A = 1.9779984951*l_ - 2.4285922050*m_ + 0.4505937099*s_;
        let B = 0.0259040371*l_ + 0.7827717662*m_ - 0.8086757660*s_;
        
        return [L, A, B];
    }

    static toOklab(r, g, b) {
        let [L, A, B] = this.toOklabParams(r, g, b);
        return `oklab(${(L * 100).toFixed(2)}% ${A.toFixed(2)} ${B.toFixed(2)})`;
    }

    static toOklch(r, g, b) {
        let [L, A, B] = this.toOklabParams(r, g, b);
        let C = Math.sqrt(A * A + B * B);
        let h = Math.atan2(B, A) * (180 / Math.PI);
        if (h < 0) h += 360;
        return `oklch(${(L * 100).toFixed(2)}% ${C.toFixed(2)} ${h.toFixed(2)})`;
    }
}

